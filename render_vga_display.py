#!/usr/bin/env python3
"""
Virtual VGA Monitor Display Generator
Simulates the exact 640x480 VGA display generated by vga_spectrum.v
for the 256-point FFT running a DDS test tone at Bin 32.
"""
import os
import sys
import numpy as np
import matplotlib.pyplot as plt

# Generate DDS tone at bin 32 (Fs/8)
N = 256
target_bin = 32
n = np.arange(N)
# Cosine tone Q1.15 amplitude ~0.85
signal = 0.85 * np.cos(2 * np.pi * target_bin * n / N)

# Compute 256-point FFT with per-stage divide-by-2 scaling
fft_raw = np.fft.fft(signal) / 256.0
# Magnitude approximation (max + 3/8 min) for bins 0..127
mag = np.zeros(128)
for k in range(128):
    re = abs(np.real(fft_raw[k])) * 32768.0
    im = abs(np.imag(fft_raw[k])) * 32768.0
    mx = max(re, im)
    mn = min(re, im)
    mag[k] = mx + 0.375 * mn

# Create 640x480 RGB framebuffer (black background)
fb = np.zeros((480, 640, 3), dtype=np.uint8)

# Baseline at y = 478, 479 (white)
fb[478:480, :, :] = 255

# Render 128 vertical bars (5 pixels wide each)
for b in range(128):
    # bar_height = min(mag >> 7, 470)
    bar_h = int(min(mag[b] / 128.0 * 2.5, 460))
    if bar_h > 0:
        x_start = b * 5
        x_end = x_start + 4
        y_top = 477 - bar_h
        # Cyan color (R=0, G=180, B=240), highlight peak at bin 32 in bright green/yellow
        if b == target_bin:
            fb[y_top:478, x_start:x_end, :] = [50, 255, 100]  # Peak highlight
        elif b == 0:
            fb[y_top:478, x_start:x_end, :] = [100, 100, 100] # DC bin
        else:
            fb[y_top:478, x_start:x_end, :] = [0, 200, 220]   # Cyan bar

# Plot and save
plt.figure(figsize=(10, 7.5), facecolor='black')
plt.imshow(fb)
plt.title(f"Virtual VGA Spectrum Display (640x480 @ 60Hz)\nPeak Detected at Bin 32 (fs/8) | Amplitude: Q1.15", 
          color='white', fontsize=14, pad=15)
plt.xlabel("VGA Horizontal Pixel (128 Bins x 5 px/bin)", color='white', fontsize=11)
plt.ylabel("VGA Vertical Scanline (0 to 479)", color='white', fontsize=11)
plt.tick_params(colors='white')
plt.grid(color='#333333', linestyle='--', linewidth=0.5)

# Annotation for peak
plt.annotate(f"PEAK: Bin 32\n(Tone at fs/8)", xy=(target_bin * 5 + 2, 477 - int(mag[target_bin] / 128.0 * 2.5)), 
             xytext=(target_bin * 5 + 30, 120),
             color='yellow', fontsize=12, fontweight='bold',
             arrowprops=dict(facecolor='yellow', shrink=0.08, width=1.5, headwidth=8))

out_path = os.path.join(r"C:\Users\user\Desktop\RTL_Project", "vga_display_virtual.png")
artifact_path = os.path.join(r"C:\Users\user\.gemini\antigravity\brain\4800233d-a733-4d47-a922-1bf1e98f099d", "vga_display_virtual.png")
plt.tight_layout()
plt.savefig(out_path, dpi=150, facecolor='black')
plt.savefig(artifact_path, dpi=150, facecolor='black')
plt.close()
print(f"Virtual VGA saved to {out_path} and {artifact_path}")
